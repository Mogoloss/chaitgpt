    hp = doc.add_paragraph(style="Heading 1")
    hr = hp.add_run(slide["title"])
    set_run_font(hr, name="黑体", size=14, bold=True)

    tp = doc.add_paragraph()
    tp.paragraph_format.line_spacing = 1.5
    tr = tp.add_run(f"建议时长：{slide['time']}")
    set_run_font(tr, name="黑体", size=11, bold=True, color=RGBColor(0, 112, 192))

    for text in slide["script"]:
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0.74)
        p.paragraph_format.line_spacing = 1.5
        r = p.add_run(text)
