function Find-Range($doc, $text) {
    $range = $doc.Content
    $find = $range.Find
    $find.ClearFormatting() | Out-Null
    $find.Text = $text
    $find.Forward = $true
    $find.Wrap = 0
    $found = $find.Execute()
    if (-not $found) {
        throw "未找到文本: $text"
    }
    return $range
}

function Replace-Between($doc, $startText, $endText, $newBody) {
    $startRange = Find-Range $doc $startText
    $searchStart = $doc.Range($startRange.End, $doc.Content.End)
    $find = $searchStart.Find
    $find.ClearFormatting() | Out-Null
    $find.Text = $endText
    $find.Forward = $true
    $find.Wrap = 0
    $found = $find.Execute()
    if (-not $found) {
        throw "未找到文本: $endText"
    }
    $target = $doc.Range($startRange.End, $searchStart.Start)
    $target.Text = "`r" + $newBody.Trim() + "`r"
}

